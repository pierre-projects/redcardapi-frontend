/** Whether interface strings exist for this language (beyond English). */
export function hasMessages(code) {
  return Boolean(MESSAGES[code]);
}

/**
 * Translator for one language: t("share") → localized string or English.
 * The returned function exposes .lang — the language the strings are in —
 * so callers can set lang/dir on the element that shows them.
 */
export function getTranslator(code) {
  const table = MESSAGES[code];
  const t = (key) => table?.[key] ?? MESSAGES.en[key] ?? key;
  t.lang = table ? code : "en";
  return t;
}
